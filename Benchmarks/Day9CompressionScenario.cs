    public static string Normalize(string value) => new(value.ToLowerInvariant().Replace('ё', 'е')
        .Where(char.IsLetterOrDigit).ToArray());

    public static bool IsCorrect(MemoryProbe probe, string answer)
    {
        string normalized = Normalize(answer);
        if (normalized.Contains("неизвестно")) return false;
        // Binary answers are exact; other facts may be surrounded by a short explanation.
        if (probe.Accepted.All(value => value is "да" or "нет"))
            return probe.Accepted.Contains(normalized);

        return probe.Accepted.Any(alternative => alternative.Split('|').All(fragment =>
        {
            string expected = Normalize(fragment);
            int start = normalized.IndexOf(expected, StringComparison.Ordinal);
            while (start >= 0)
            {
                int end = start + expected.Length;
                bool left = !char.IsDigit(expected[0]) || start == 0 || !char.IsDigit(normalized[start - 1]);
                bool right = !char.IsDigit(expected[^1]) || end == normalized.Length || !char.IsDigit(normalized[end]);
                if (left && right) return true;
                start = normalized.IndexOf(expected, start + 1, StringComparison.Ordinal);
            }

            return false;
        }));
    }
